"""
Build src/data/fe1/fe1Units.ts from the user's own Fire Emblem: Shadow Dragon and the Blade of Light (the Switch release of the
Famicom original; see data-raw/fe1/README.md): the playable units, when and how they join, their classes and promotions.

Run: python scripts/build-fe1-units.py   (FE1_NSP overrides where the package is; the keys are in ~/.switch)
"""
import json
import os

from fe1_units import build, load

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'src', 'data', 'fe1', 'fe1Units.ts')
STATS = ['hp', 'str', 'skl', 'wlv', 'spd', 'lck', 'def', 'res', 'mov']
GROWING = ['hp', 'str', 'skl', 'wlv', 'spd', 'lck', 'def']
# A recruited foe's Luck is a random 0 to 7 (3:$8E52): the planner starts from its average.
RANDOM_LUCK = 3.5


def main():
    data = build(load())
    chapters = [{'id': f"fe1-{c['number']}", 'label': f"Ch.{c['number']}"} for c in data['chapters']]
    by_id = {int(k): c for k, c in data['classes'].items()}
    targets = {c['promotesTo'] for c in by_id.values() if c.get('promotesTo')}
    used = set()
    units = []
    for u in sorted(data['units'], key=lambda u: (u['joinChapter'], u['character'])):
        bases = {s: u['bases'][s] for s in STATS}
        if bases['lck'] is None:
            bases['lck'] = RANDOM_LUCK
        units.append({
            'id': f"fe1-{u['character']}", 'name': u['name'], 'classId': str(u['class']), 'level': u['level'],
            'joinChapter': f"fe1-{u['joinChapter']}", 'join': u['join'], 'bases': bases,
            'growths': {s: u['growths'][s] for s in GROWING}, 'ranks': {},
        })
        used.add(u['class'])
    used |= {by_id[c]['promotesTo'] for c in used if by_id[c].get('promotesTo')}
    classes = {}
    for k in sorted(used):
        c = by_id[k]
        entry = {'id': str(k), 'name': c['name'], 'bases': {**{s: c['bases'].get(s, 0) for s in STATS}},
                 'caps': c['caps'], 'maxLevel': c['maxLevel']}
        if c.get('promotesTo'):
            entry['promotesTo'] = str(c['promotesTo'])
        if k in targets:
            entry['promoted'] = True
        classes[str(k)] = entry

    def js(v):
        return json.dumps(v, ensure_ascii=False)

    lines = [
        "// Generated by scripts/build-fe1-units.py from the user's own Shadow Dragon and the Blade of Light (Switch). Don't edit by hand.",
        "import type { GbaChapter, GbaClass, GbaUnit } from '../../gba/types'",
        '',
        f'export const FE1_CHAPTERS: GbaChapter[] = {js(chapters)}',
        '',
        'export const FE1_UNITS: GbaUnit[] = [',
        *[f'  {js(u)},' for u in units],
        ']',
        '',
        'export const FE1_CLASSES: Record<string, GbaClass> = {',
        *[f'  {js(k)}: {js(v)},' for k, v in classes.items()],
        '}',
        '',
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print(f'{len(units)} units, {len(classes)} classes, {len(chapters)} chapters -> {OUT}')


if __name__ == '__main__':
    main()
