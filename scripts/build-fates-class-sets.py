"""
Write src/data/__tests__/fatesGameClassSets.ts: every first-generation unit's Heart Seal class set as Fates' own GameData.bin has
it, for the tests to hold the hand-entered class sets in src/data/characters.ts to. See data-raw/fates/README.md for the formats.

Reads the romfs the Fire Emblem Armory extracted from the user's cartridge (../Fates Armory/data-raw/fates/romfs; FATES_ROMFS
overrides it). Never commits anything from it but these derived names. Run:
    python scripts/build-fates-class-sets.py
"""
import glob
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fates_text  # noqa: E402
from fates_lz import decompress  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ROMFS = os.environ.get('FATES_ROMFS', os.path.join(ROOT, '..', 'Fates Armory', 'data-raw', 'fates', 'romfs'))
OUT = os.path.join(ROOT, 'src', 'data', '__tests__', 'fatesGameClassSets.ts')
B = 0x20
JOB, PERSON = 0x80, 0x98  # record sizes, counted from each record's ID pointer (an 8-byte flag word sits before it)
PROMOTED = 3  # class flag bit: SPID_上級職


def main():
    d = decompress(open(os.path.join(ROMFS, 'GameData.bin.lz'), 'rb').read())
    u16 = lambda o: struct.unpack_from('<H', d, o)[0]  # noqa: E731
    u32 = lambda o: struct.unpack_from('<I', d, o)[0]  # noqa: E731

    def s(ptr):
        o = B + ptr
        if not 0 < ptr < len(d) - B:
            return None
        try:
            return d[o:d.index(b'\0', o)].decode('shift_jis')
        except (ValueError, UnicodeDecodeError):
            return None

    text = {}
    for path in glob.glob(os.path.join(ROMFS, 'm', '@E', '*.bin.lz')):
        text.update(fates_text.read(path))

    def table(prefix, size):
        first = next(o for o in range(B, len(d) - 4, 4) if (s(u32(o)) or '').startswith(prefix))
        out = []
        o = first
        while (s(u32(o)) or '').startswith(prefix):
            out.append(o)
            o += size
        return out

    jobs = {u16(o + 0x10): o for o in table('JID_', JOB)}  # +0x10: the class number

    def job_name(n):
        return text[s(u32(jobs[n] + 8))]  # +8: the class's name label (MJID_)

    def promoted(n):
        return int.from_bytes(d[jobs[n] - 8:jobs[n]], 'little') >> PROMOTED & 1

    sets = {}
    for o in table('PID_', PERSON):
        # +0x24 the class, +0x26 the other one; the default is whichever is a base class (the program's 0x53e1b0). +0x74 and +0x76:
        # the two reclass slots. Children (+0x22: their fixed parent) have none; theirs come from their parents.
        reclass = [u16(o + 0x74), u16(o + 0x76)]
        if not reclass[0] or u16(o + 0x22):
            continue
        cls = u16(o + 0x24)
        default = u16(o + 0x26) if promoted(cls) else cls
        name = text.get(s(u32(o + 0x0c)) or '')
        if name and name not in sets:
            sets[name] = [job_name(n) for n in [default] + reclass if n]
    lines = [
        '// Generated by scripts/build-fates-class-sets.py from GameData.bin (data-raw/fates/README.md). Do not edit by hand.',
        '/** Every first-generation unit\'s Heart Seal class set in the game\'s own data: default class, then its reclass slots. */',
        'export const FATES_GAME_CLASS_SETS: Record<string, string[]> = {',
    ]
    quote = lambda t: "'" + t.replace("'", "\\'") + "'"  # noqa: E731
    lines += [f"  {quote(name)}: [{', '.join(map(quote, classes))}]," for name, classes in sorted(sets.items())]
    lines.append('}')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print(f'{len(sets)} class sets -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
